package it.polimi.ingsw.enumerations;

/**
 * Represents the symbols associated with crafter cards.
 *
 * <p>Each symbol identifies a specific type of crafted item, owned by the crafter, that in
 * combination with other crafter items give bonus PPs at the end of the game.</p>
 */
public enum CrafterSymbolEnum {

    /** The amygdala symbol. */
    AMIGDALA,

    /** The arrowhead symbol. */
    ARROWHEAD,

    /** The hook symbol. */
    HOOK,

    /** The necklace symbol. */
    NECKLACE,

    /** The bowl symbol. */
    BOWL,

    /** The rope symbol. */
    ROPE,

    /** The doll symbol. */
    DOLL,

    /** The flute symbol. */
    FLUTE,

    /** The leather symbol. */
    LEATHER,

    /** The bread symbol. */
    BREAD
}
